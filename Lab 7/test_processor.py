"""Property-based tests for the three Lab 7 input-processing functions."""

import math

from hypothesis import given, strategies as st

from processor import (
    INVALID_RECORD,
    sanitize_license_plate,
    parse_trip_mileage,
    format_rental_invoice,
)


# 1. Arbitrary strings and None must never crash license-plate sanitization.
@given(st.one_of(st.text(), st.none()))
def test_sanitize_license_plate_no_crash(value):
    result = sanitize_license_plate(value)
    assert isinstance(result, str)
    assert not any(delimiter in result for delimiter in ("-", " ", "_", "#"))
    assert result == result.upper()


# 2. Arbitrary strings and None must never crash mileage parsing.
@given(st.one_of(st.text(), st.none()))
def test_parse_trip_mileage_safe(value):
    result = parse_trip_mileage(value)
    assert isinstance(result, list)
    assert all(isinstance(item, float) for item in result)
    assert all(math.isfinite(item) and item >= 0 for item in result)


# 3. Arbitrary strings and None must never crash invoice formatting.
@given(st.one_of(st.text(), st.none()))
def test_format_rental_invoice_safe(value):
    result = format_rental_invoice(value)
    assert isinstance(result, str)


# Valid-input properties generated by Hypothesis.
@given(
    driver=st.text(min_size=1).filter(lambda value: ":" not in value and value.strip() != ""),
    days=st.integers(min_value=1, max_value=10000),
    category=st.sampled_from(["SUV", "suv", "Sedan", "Hatchback"]),
)
def test_valid_rental_invoice_calculates_expected_total(driver, days, category):
    result = format_rental_invoice(f"{driver}:{days}:{category}")
    rate = 50.0 if category.lower() == "suv" else 30.0
    expected = f"Driver {driver.strip()} booked {category.strip()} for {days} days: Total ${days * rate:.2f}"
    assert result == expected


# Explicit regression tests for important edge cases.
def test_sanitize_license_plate_examples():
    assert sanitize_license_plate(" ka-01_ab#1234 ") == "KA01AB1234"
    assert sanitize_license_plate(None) == ""


def test_parse_trip_mileage_examples():
    assert parse_trip_mileage("100.5, 45.2, 80.0") == [100.5, 45.2, 80.0]
    assert parse_trip_mileage("") == []
    assert parse_trip_mileage("1,,3") == []
    assert parse_trip_mileage("1,NaN,3") == []
    assert parse_trip_mileage("-1,2") == []
    assert parse_trip_mileage(None) == []


def test_format_rental_invoice_examples():
    assert format_rental_invoice("Asha:2:SUV") == (
        "Driver Asha booked SUV for 2 days: Total $100.00"
    )
    assert format_rental_invoice("Asha:2:Sedan") == (
        "Driver Asha booked Sedan for 2 days: Total $60.00"
    )
    assert format_rental_invoice("Asha:0:SUV") == INVALID_RECORD
    assert format_rental_invoice("Asha:two:SUV") == INVALID_RECORD
    assert format_rental_invoice("Asha:2") == INVALID_RECORD
    assert format_rental_invoice(None) == INVALID_RECORD
